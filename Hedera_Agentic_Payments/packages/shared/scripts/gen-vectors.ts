/**
 * Generates vectors/trust.json from the TS reference maths.
 * Lane C's Foundry tests must reproduce every expected value exactly.
 * Run: pnpm --filter @tmb/shared vectors
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  newExporterRep, newImporterRep, applyExporterOutcome, applyImporterOutcome, score, terms, waterfall,
  dealOutcome, type Checks, type ImporterOutcome, type Rep,
} from "../src/trust.ts";

const T: Checks = { weight: true, statusCode: true, documents: true };
const s = (x: bigint) => x.toString();
const repJson = (r: Rep) => ({ r: s(r.r), s: s(r.s), a: s(r.a), b: s(r.b) });

type Step = { claims: Checks; observed: Checks };
const exporterSequences: Record<string, Step[]> = {
  "five honest deals": Array(5).fill({ claims: T, observed: T }),
  "fake weight from new": [{ claims: T, observed: { ...T, weight: false } }],
  "fake status from new": [{ claims: T, observed: { ...T, statusCode: false } }],
  "fake docs from new": [{ claims: T, observed: { ...T, documents: false } }],
  "fake weight and docs from new": [{ claims: T, observed: { weight: false, statusCode: true, documents: false } }],
  "veteran then fake weight": [...Array(5).fill({ claims: T, observed: T }), { claims: T, observed: { ...T, weight: false } }],
  "understated docs is neutral": [{ claims: { ...T, documents: false }, observed: T }],
  "honest, lie, honest": [{ claims: T, observed: T }, { claims: T, observed: { ...T, weight: false } }, { claims: T, observed: T }],
};

const importerSequences: Record<string, { trustCodeBps: bigint; outcomes: ImporterOutcome[] }> = {
  "80% importer pays on time x3": { trustCodeBps: 8000n, outcomes: ["onTime", "onTime", "onTime"] },
  "80% importer late once": { trustCodeBps: 8000n, outcomes: ["late"] },
  "80% importer defaults": { trustCodeBps: 8000n, outcomes: ["default"] },
  "60% importer on time then default": { trustCodeBps: 6000n, outcomes: ["onTime", "default"] },
};

const exporter = Object.entries(exporterSequences).map(([name, steps]) => {
  let rep = newExporterRep();
  const after = steps.map((st) => {
    const o = dealOutcome(st.claims, st.observed);
    rep = applyExporterOutcome(rep, st.claims, st.observed);
    return { claims: st.claims, observed: st.observed, falsified: o.falsified, positive: s(o.positive), negative: s(o.negative), rep: repJson(rep), score: s(score(rep)) };
  });
  return { name, start: repJson(newExporterRep()), steps: after };
});

const importer = Object.entries(importerSequences).map(([name, seq]) => {
  let rep = newImporterRep(seq.trustCodeBps);
  const start = repJson(rep);
  const steps = seq.outcomes.map((outcome) => {
    rep = applyImporterOutcome(rep, outcome);
    return { outcome, rep: repJson(rep), score: s(score(rep)) };
  });
  return { name, trustCodeBps: s(seq.trustCodeBps), start, startScore: s(score(newImporterRep(seq.trustCodeBps))), steps };
});

const termCases = [0n, 2631n, 5000n, 6666n, 7500n, 8000n, 8571n, 9000n, 10000n].flatMap((e) =>
  [5000n, 8000n, 9000n].map((i) => {
    const t = terms(e, i);
    return { exporterScore: s(e), importerScore: s(i), advanceBps: s(t.advanceBps), yieldBps: s(t.yieldBps) };
  }),
);

const U = 1_000_000n; // 6-decimals token
const waterfallCases = [
  { name: "new exporter, 80% importer", invoice: 30000n * U, exp: 5000n, imp: 8000n, fee: 150n * U },
  { name: "veteran pair (PDF example)", invoice: 30000n * U, exp: 9000n, imp: 9000n, fee: 150n * U },
  { name: "3 honest deals, 80% importer", invoice: 30000n * U, exp: 8000n, imp: 8000n, fee: 150n * U },
  { name: "small demo invoice 30 USDT", invoice: 30n * U, exp: 5000n, imp: 8000n, fee: 150_000n },
].map((c) => {
  const t = terms(c.exp, c.imp);
  const w = waterfall({ invoice: c.invoice, advanceBps: t.advanceBps, yieldBps: t.yieldBps, fee: c.fee });
  return {
    name: c.name, invoice: s(c.invoice), fee: s(c.fee), advanceBps: s(t.advanceBps), yieldBps: s(t.yieldBps),
    advance: s(w.advance), investors: s(w.investors), exporterRemainder: s(w.exporterRemainder),
  };
});

const out = {
  version: 1,
  note: "Generated by packages/shared/scripts/gen-vectors.ts. All values in bps (10000 = 100%) or token atomic units (6 dp).",
  constants: { BPS: "10000", W_WEIGHT: "4000", W_STATUS: "2500", W_DOCS: "3500", FRAUD_MULT: "2", EXPORTER_PRIOR_A: "10000", EXPORTER_PRIOR_B: "10000", IMPORTER_PRIOR_STRENGTH: "20000" },
  exporter, importer, terms: termCases, waterfall: waterfallCases,
};

const here = dirname(fileURLToPath(import.meta.url));
const file = join(here, "..", "vectors", "trust.json");
mkdirSync(dirname(file), { recursive: true });
writeFileSync(file, JSON.stringify(out, null, 2) + "\n");
console.log(`wrote ${file}: ${exporter.length} exporter, ${importer.length} importer, ${termCases.length} terms, ${waterfallCases.length} waterfall cases`);
