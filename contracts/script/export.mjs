#!/usr/bin/env node
// Copies contract ABIs (from Foundry's out/) and deployments (from deployments/*.json) into
// packages/shared/src so the dashboard and the agent import one source of truth.
//
//   cd contracts && forge build && node script/export.mjs

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const contractsDir = join(dirname(fileURLToPath(import.meta.url)), "..")
const sharedSrc = join(contractsDir, "..", "packages", "shared", "src")
const abiDir = join(sharedSrc, "abi")
const header = "// Generated by contracts/script/export.mjs. Do not edit by hand.\n"

const artifacts = [
  { contract: "TradeDeals", exportName: "tradeDealsAbi", file: "tradeDeals.ts" },
  { contract: "TrustRegistry", exportName: "trustRegistryAbi", file: "trustRegistry.ts" },
]

mkdirSync(abiDir, { recursive: true })

for (const { contract, exportName, file } of artifacts) {
  const artifactPath = join(contractsDir, "out", `${contract}.sol`, `${contract}.json`)
  if (!existsSync(artifactPath)) {
    console.error(`Missing ${artifactPath}. Run "forge build" in contracts/ first.`)
    process.exit(1)
  }
  const { abi } = JSON.parse(readFileSync(artifactPath, "utf8"))
  writeFileSync(
    join(abiDir, file),
    `${header}export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const\n`,
  )
  console.log(`abi  ${contract} -> packages/shared/src/abi/${file}`)
}

writeFileSync(
  join(abiDir, "index.ts"),
  `${header}export { erc20Abi } from "./erc20"\n` +
    artifacts.map((a) => `export { ${a.exportName} } from "./${a.file.replace(/\.ts$/, "")}"\n`).join(""),
)

const deploymentsDir = join(contractsDir, "deployments")
const deployments = {}
if (existsSync(deploymentsDir)) {
  for (const name of readdirSync(deploymentsDir)) {
    if (!/^\d+\.json$/.test(name)) continue
    const deployment = JSON.parse(readFileSync(join(deploymentsDir, name), "utf8"))
    deployments[deployment.chainId] = deployment
    console.log(`deployment chain ${deployment.chainId}: TradeDeals ${deployment.tradeDeals}`)
  }
}
writeFileSync(
  join(sharedSrc, "deployments.ts"),
  `${header}export const deployments = ${JSON.stringify(deployments, null, 2)} as const\n`,
)
console.log("wrote packages/shared/src/deployments.ts")
