// Signs one Verification with viem, using the shared EIP-712 definition, and writes
// contracts/test/fixtures/eip712.json. contracts/test/Eip712RoundTrip.t.sol then checks that
// Solidity computes the same digest and accepts the signature.
//
//   cd packages/shared && npm install && npm run fixture
//   cd ../../contracts && forge test --match-contract Eip712RoundTrip -vv

import { mkdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import { hashTypedData, keccak256, stringToBytes } from "viem"
import { privateKeyToAccount } from "viem/accounts"

import {
  dealIdToBytes32,
  verificationDomain,
  verificationTypes,
  type Address,
  type VerificationMessage,
} from "../src/eip712"
import { ShipmentStatus } from "../src/constants"

// Throwaway key that exists only for this fixture (anvil's public test account #1). Never fund it.
const FIXTURE_KEY = "0x59c6995e998f97a5a0044966f0945389dc9e86dae88c7a8412f4603b6b78690d"
// The forge test deploys TradeDeals at exactly this address.
const VERIFYING_CONTRACT: Address = "0x1874000000000000000000000000000000001874"

const message: VerificationMessage = {
  dealId: dealIdToBytes32(1n),
  observedKg: 9_850, // within ±3% of the 10,000 kg the test claims
  statusCode: ShipmentStatus.DEPARTED,
  docHash: keccak256(stringToBytes("TrustMeBro fixture: invoice + packing list + bill of lading")),
  observedAt: 1_800_000_000n,
  nonce: 42n,
  expiry: 1_900_000_000n,
}

const account = privateKeyToAccount(FIXTURE_KEY)
const domain = verificationDomain(VERIFYING_CONTRACT)
const typed = { domain, types: verificationTypes, primaryType: "Verification", message } as const

const signature = await account.signTypedData(typed)
const digest = hashTypedData(typed)

const fixture = {
  note: "Generated by packages/shared/scripts/eip712-fixture.ts. Do not edit by hand.",
  signer: account.address,
  domain: { ...domain, chainId: String(domain.chainId) },
  message: {
    dealId: message.dealId,
    observedKg: String(message.observedKg),
    statusCode: String(message.statusCode),
    docHash: message.docHash,
    observedAt: message.observedAt.toString(),
    nonce: message.nonce.toString(),
    expiry: message.expiry.toString(),
  },
  digest,
  signature,
}

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "contracts", "test", "fixtures", "eip712.json")
mkdirSync(dirname(out), { recursive: true })
writeFileSync(out, `${JSON.stringify(fixture, null, 2)}\n`)
console.log(`signer ${account.address}\ndigest ${digest}\nwrote  ${out}`)
